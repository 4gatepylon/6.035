class TypePropTester extends FunSuite {
  val blankProgram = ASTProgram(
    IdToken("void", 1, 1),
    // No imports
    List(),
    // No fields
    List(),
    // No Method
    List()
  )
  val blankTable = Symbols(blankProgram, parent = None)

  // Expression: test (declared as bool test)
  def testTypeScalar(dtype: ReturnType.Type, typeString: String): Boolean = {
    // First you have to declare it
    // NOTE you need to wrap it in a field declaration
    // (the table describe method gets its parent to find the type
    // from the field... maybe not ideal but whatever)
    val field = ASTFieldDecl(
      // Has a token (NOTE that in the scanner types are checked
      // before keywords, so keyword is mainly keywords that
      // are not types)
      TypeToken(typeString, 0, 0),
      // And a type
      ASTTypeNode(TypeToken(typeString, 0, 0)),
      // And a list of variables
      List(
        ASTScalarDecl(
          IdToken("test", 0, 0),
          ASTIdNode(IdToken("test", 0, 0))
        )
      )
    )

    var table = blankTable
    for (declr <- field.vars) {
      // Unclear where in Julius' code the parent is set but we can assume that he does set it
      declr.parent = Some(field)
      val description = TableInserter.describe(declr)
      table = table.addedScalar(description.asInstanceOf[ScalarDescr])
    }
    // Then you can try and get it
    val location =
      ASTScalarLocation(IdToken("test", 0, 0), ASTIdNode(IdToken("test", 0, 0)))
    location.table = table
    location.id.table = table
    val returnExpected = dtype
    val returnGot = TypeProp.visit(location)
    // println(s"got ${returnGot} from ${table}")
    return returnExpected == returnGot
  }

  test(
    "`TypeProp` test: ScalarLocation of BoolType propagates BoolType"
  ) {
    assert(testTypeScalar(ReturnType.bool, "bool"))
  }

  // Expression: test (declared as int test)
  test(
    "`TypeProp` test: ScalarLocation of IntType propagates IntType"
  ) {
    assert(testTypeScalar(ReturnType.int, "int"))
  }

