  def testTypeMethod(dtype: ReturnType.Type, typeString: String): Boolean = {
    // We must have a method declaration
    // Which then we imagine was "visited"
    // and thus loaded into the table
    // Then we have an expression (differnet from the declaration)
    // that we test for return type (should go into the table and find the
    // return type of the declaration)

    // token: Keyword,
    // id: IdNode,
    // params: List[Param],
    // block: Block
    val declr: ASTTypeMethodDecl = ASTTypeMethodDecl(
      // Token
      TypeToken(typeString, 0, 0),
      // Type
      ASTTypeNode(TypeToken(typeString, 0, 0)),
      // Method name
      ASTIdNode(IdToken("test", 0, 0)),
      // No arguments
      List(),
      // Declaration
      ASTBlock(
        // Methods must start like this
        Mark("{", 0, 0),
        // No fields
        List(),
        // No statements
        List()
      )
    )

    // Technically not legal, so might not pass later, but whatever
    val expr: ASTMethodCallExpr = ASTMethodCallExpr(
      // Token
      IdToken("test", 0, 0),
      // MethodName (not sure why it was just IdNode for declr)
      ASTMethodName(
        // Token
        IdToken("test", 0, 0),
        // Id node with token in it
        ASTIdNode(IdToken("test", 0, 0))
      ),
      // Arguments (none, but if so would have to have type Param from the nodes)
      // token: Token, dtype: TypeNode, id: IdNode
      List()
    )

    val description: Descr = TableInserter.describe(declr)
    val table = blankTable.addedMethod(description.asInstanceOf[MethodDescr])

    expr.table = table
    expr.name.id.table = table
    val returnExpected = dtype
    val returnGot = TypeProp.visit(expr)
    return returnExpected == returnGot;
  }

